#!/usr/bin/env python3
"""Generates static symbol tables that stand in for dlopen/dlsym on Horizon.

For every library, the P/Invoke entry points are collected from the C# bindings
and kept only if the static archives actually define them, so a missing native
function shows up at generation time instead of as a crash on console.

usage: gen_dlshim.py <out.c> <nm-binary> <lib-spec>...
lib-spec: Name=binding1.cs[,binding2.cs]:archive1.a[,archive2.a]
"""
import re
import subprocess
import sys

DLLIMPORT_RE = re.compile(
    r'\[DllImport\((?P<args>[^\]]*)\)\]\s*'
    r'(?:\[[^\]]*\]\s*)*'
    r'(?:(?:public|private|internal|static|extern|unsafe|new)\s+)+'
    r'[\w.<>\[\]*]+\s+(?P<name>\w+)\s*\(',
    re.S,
)
ENTRY_RE = re.compile(r'EntryPoint\s*=\s*"(\w+)"')


def binding_symbols(path):
    text = open(path, encoding='utf-8-sig').read()
    names = set()
    for m in DLLIMPORT_RE.finditer(text):
        entry = ENTRY_RE.search(m.group('args'))
        names.add(entry.group(1) if entry else m.group('name'))
    return names


def archive_symbols(nm, path):
    out = subprocess.run([nm, '--defined-only', '-g', path], capture_output=True, text=True, check=True).stdout
    return {line.split()[-1] for line in out.splitlines() if re.match(r'^[0-9a-f]+ [TW] ', line)}


def main():
    out_path, nm, specs = sys.argv[1], sys.argv[2], sys.argv[3:]
    parts = ['/* Generated by gen_dlshim.py, do not edit. */', '#include <stdlib.h>', '#include <string.h>', '',
             'typedef struct { const char *name; void *addr; } DlShimSymbol;', '',
             'static int dlshim_cmp(const void *key, const void *item)',
             '{', '\treturn strcmp((const char *)key, ((const DlShimSymbol *)item)->name);', '}', '']
    for spec in specs:
        name, rest = spec.split('=', 1)
        bindings, archives = rest.split(':', 1)
        wanted = set()
        for b in bindings.split(','):
            wanted |= binding_symbols(b)
        available = set()
        for a in archives.split(','):
            available |= archive_symbols(nm, a)
        resolved = sorted(wanted & available)
        missing = sorted(wanted - available)
        print(f'{name}: {len(resolved)} resolved, {len(missing)} missing', file=sys.stderr)
        for sym in missing:
            print(f'  missing {name}.{sym}', file=sys.stderr)
        parts += [f'extern void {sym}(void);' for sym in resolved]
        parts += ['', f'static const DlShimSymbol dlshim_table_{name}[] = {{']
        parts += [f'\t{{"{sym}", (void *){sym}}},' for sym in resolved]
        parts += ['};', '',
                  f'void *getsym_{name}(const char *name)', '{',
                  f'\tconst DlShimSymbol *s = bsearch(name, dlshim_table_{name}, '
                  f'sizeof(dlshim_table_{name}) / sizeof(DlShimSymbol), sizeof(DlShimSymbol), dlshim_cmp);',
                  '\treturn s ? s->addr : NULL;', '}', '']
    open(out_path, 'w').write('\n'.join(parts))


if __name__ == '__main__':
    main()
